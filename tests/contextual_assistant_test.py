from pathlib import Path
from playwright.sync_api import sync_playwright
p=Path(__file__).resolve().parents[1]/'index.html'
html=p.read_text()
with sync_playwright() as pw:
  browser=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
  context=browser.new_context(viewport={'width':1280,'height':850},accept_downloads=True)
  page=context.new_page();errors=[]
  page.on('pageerror',lambda e:errors.append(str(e)))
  page.on('dialog',lambda d:d.accept())
  page.evaluate("Object.defineProperty(window,'localStorage',{value:{store:{},getItem(k){return this.store[k]||null},setItem(k,v){this.store[k]=v},removeItem(k){delete this.store[k]}},configurable:true})")
  page.set_content(html)
  def passed(label,truth):
    if not truth:raise AssertionError(label+'; errors '+str(errors)+'; status '+page.locator('#v13MilestoneOutput').inner_text()[:500])
    print('PASS:',label)
  passed('seeded projects present',page.evaluate('db.items.length')==5)
  page.locator('[data-tab="apply"]').click()
  page.locator('#v13ApplicationCheck').click()
  passed('missing required information flagged', 'incomplete' in page.locator('#v13ApplicationOutput').inner_text().lower())
  page.locator('[name="name"]').fill('Dr. Fiona Grant')
  page.locator('[name="email"]').fill('fiona@fictional.test')
  page.locator('[name="org"]').fill('Fictional University')
  page.locator('[name="title"]').fill('Research Benchmark for Agents')
  page.locator('[name="description"]').fill('This fictional benchmark examines real world benchmark grading consistency, comparative outcomes and quality assessment via human raters.')
  page.locator('[name="difference"]').fill('Short')
  page.locator('[name="method"]').fill('Independent evaluation, reviewer adjudication, documented task scenarios and expert review sessions.')
  page.locator('[name="duration"]').fill('12 months')
  page.locator('[name="terms"]').check()
  page.locator('#v13ApplicationCheck').click()
  t=page.locator('#v13ApplicationOutput').inner_text()
  passed('required fields complete; discretionary clarification suggested', 'no missing required fields' in t.lower() and 'clarification' in t.lower())
  page.locator('#form button[type="submit"], #form button:not([type])').first.click()
  passed('original submit workflow still records application',page.evaluate('db.items.length')==6)
  page.locator('[data-tab="milestones"]').click()
  passed('milestone assistant has active-project context',page.locator('#v13MilestoneSelect option').count()>0)
  page.locator('#v13MilestoneCheck').click()
  passed('cannot run without narrative','Enter a progress narrative' in page.locator('#v13MilestoneOutput').inner_text())
  page.locator('#v13MilestoneProgress').fill('We documented grading reliability, task specifications and long-running agents using annotated reference cases with human review.')
  page.locator('#v13MilestoneCheck').click()
  passed('milestone comparison recorded',page.evaluate("Boolean(db.items.find(p=>p.id==='OBG-001').milestones[0].comparison)"))
  passed('human review available inline',page.locator('#v13MilestoneReview').is_visible())
  page.locator('#v13MilestoneReviewer').fill('Demo Scientific Reviewer')
  page.locator('#v13MilestoneDecision').select_option('Aligned')
  page.locator('#v13MilestoneRationale').fill('Submission narrative addresses milestone requirements; fictional evidence requires review.')
  page.locator('#v13MilestoneSaveReview').click()
  passed('assessment saved to original scope review history',page.evaluate("db.items.find(p=>p.id==='OBG-001').scopeReview.assessments[0].decision==='Aligned'"))
  passed('audit history updated',page.evaluate("db.audit.some(a=>a.action.includes('Human milestone assessment from milestone workflow'))"))
  passed('saved assessment shown', 'Human review recorded' in page.locator('#v13MilestoneOutput').inner_text())
  passed('no JavaScript errors',not errors)
  browser.close()
